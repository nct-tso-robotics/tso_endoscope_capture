# Rebuild ROS search paths from the selected environment: the calling shell may
# already source a different ROS distribution. Keep deployment addresses intact.
if [ "${PIXI_ENVIRONMENT_NAME:-}" = ros1 ] || [ "${PIXI_ENVIRONMENT_NAME:-}" = ros2 ]; then
  # Explicit empty exports also override inherited values in Pixi's activation
  # result; an unset variable alone can be inherited again by the task process.
  export ROS_ROOT="" ROS_PACKAGE_PATH="" PYTHONPATH="" AMENT_PREFIX_PATH="" COLCON_PREFIX_PATH=""
  unset AMENT_CURRENT_PREFIX _CATKIN_SETUP_DIR
  export CMAKE_PREFIX_PATH="$CONDA_PREFIX"
  export LD_LIBRARY_PATH="$CONDA_PREFIX/lib"
  if [ "$PIXI_ENVIRONMENT_NAME" = ros2 ]; then
    . "$CONDA_PREFIX/local_setup.sh"
    if [ -f "$PIXI_PROJECT_ROOT/build/ros2/.install/share/endoscope_capture/local_setup.sh" ]; then
      # This package is built directly with CMake, so use its package setup
      # rather than a workspace-level setup normally generated by colcon.
      AMENT_CURRENT_PREFIX="$PIXI_PROJECT_ROOT/build/ros2/.install"
      . "$AMENT_CURRENT_PREFIX/share/endoscope_capture/local_setup.sh"
      export LD_LIBRARY_PATH="$PIXI_PROJECT_ROOT/build/ros2/.install/lib:$LD_LIBRARY_PATH"
      export CMAKE_PREFIX_PATH="$PIXI_PROJECT_ROOT/build/ros2/.install:$CMAKE_PREFIX_PATH"
      unset AMENT_CURRENT_PREFIX
    fi
  else
    . "$CONDA_PREFIX/setup.sh"
    if [ -x "$PIXI_PROJECT_ROOT/build/ros/devel/lib/endoscope_capture/endoscope_capture_node" ]; then
      . "$PIXI_PROJECT_ROOT/build/ros/devel/setup.sh" --extend
    fi
  fi
fi
export PYTHONPATH="${PYTHONPATH%:}"
export AMENT_PREFIX_PATH="${AMENT_PREFIX_PATH%:}"
